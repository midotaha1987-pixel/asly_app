/* ---------- خطوة 4 — سمّع نفسك (تصحيح ذاتي، بلا حكم آلي) ----------
   الطفل يقول الآية بصوت عالي من ذاكرته، ويدوس على كل كلمة
   يتأكد منها ويعلّمها «قلتها صح» أو «غلطت فيها» — هو اللي
   يقارن ويقرر. التطبيق يعرض النص الصحيح وصوت القارئ فقط،
   ولا يقول «صح» أو «غلط» على تلاوته أبدًا. الميكروفون غير
   مستخدم هنا — الطفل يسمّع بصوت عالي ويتأكد بالضغط. */
function darJrnMistakeSpots(r) {
  const stage = r.stage;
  const spots = [];
  r.words.forEach(function (w, i) {
    const last = i === r.words.length - 1;
    const labels = [];
    if (darJrnWordMatches(w, 'madd', last)) labels.push(stage === 1 ? 'صوت بيتمدّ' : 'المد الطبيعي');
    if (darJrnWordMatches(w, 'ghunnah', last)) labels.push(stage === 1 ? 'رنين' : 'غُنّة النون المشددة');
    if (darJrnWordMatches(w, 'qalqalah', last)) labels.push(stage === 1 ? 'نطّة' : 'القلقلة');
    if (darJrnLamNote(w, stage)) labels.push(stage === 1
      ? (w.charAt(2) === '\u0652' ? 'لام بتتقال واضحة' : 'لام مش بتتقال')
      : (w.charAt(2) === '\u0652' ? 'لام قمرية' : 'لام شمسية'));
    if (labels.length) spots.push({ word: w, idx: i, labels: labels });
  });
  return spots.slice(0, 3);
}
function darJrnMistakeCardHtml(r) {
  const spots = darJrnMistakeSpots(r);
  let h = '<div class="dar-jrn-card dar-jrn-mistake"><div class="dar-jrn-story-t">👀 خد بالك! كلمات ممكن تتلخبط فيها</div>';
  if (!spots.length) {
    h += '<p class="hint">مفيش كلمة صعبة واضحة في الآية دي — اسمعها كويس من القارئ قبل ما تسمّع.</p>';
  } else {
    h += '<p class="hint">الكلمات دي فيها أصوات محتاجة تركيز — اسمعها من القارئ الأول:</p>'
      + spots.map(function (s) {
        return '<p><span class="dar-jrn-hard-word">' + darEsc(s.word) + '</span> — ' + s.labels.map(darEsc).join(' • ') + '</p>';
      }).join('');
  }
  h += '<button class="dar-btn" id="darJrnScListenBtn" onclick="darJrnScPlayModel()">▶ اسمع الآية من القارئ</button></div>';
  return h;
}
